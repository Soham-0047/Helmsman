// `npm run benchmark` — run the Agent Society A/B, then regenerate the README
// comparison table from benchmarks/results.json (between BENCHMARK markers).
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { AGENTS, banner, env, fail, isUp, ok, ROOT, sleep, spawnRuntime, step, venvPython, waitFor } from "./lib.mjs";

const spawned = [];

async function ensureRuntime() {
  if (!(await isUp(AGENTS))) {
    step("starting agent runtime…");
    spawned.push(spawnRuntime());
    await waitFor(AGENTS, "agent runtime");
  }
}

function regenReadme(results) {
  const path = resolve(ROOT, "README.md");
  if (!existsSync(path)) return;
  const m = results.metrics;
  const pct = (x) => `${(x * 100).toFixed(0)}%`;
  const table = [
    `<!-- BENCHMARK:START -->`,
    `<!-- Auto-generated by \`npm run benchmark\` from benchmarks/results.json. Do not edit by hand. -->`,
    ``,
    `**Run:** ${results.n_issues} fixture issues · mode: \`${results.mode}\` · ${results.generated_at}`,
    ``,
    `| Metric | Single-agent baseline | Seven-agent Helmsman | Δ |`,
    `|---|---|---|---|`,
    `| Classification accuracy | ${pct(m.classification_accuracy.baseline)} | **${pct(m.classification_accuracy.pipeline)}** | ${results.deltas.classification_accuracy_pp >= 0 ? "+" : ""}${results.deltas.classification_accuracy_pp} pp |`,
    `| Response quality (1–5, LLM-judge) | ${m.response_quality_1to5.baseline.toFixed(2)} | **${m.response_quality_1to5.pipeline.toFixed(2)}** | ${results.deltas.quality_abs >= 0 ? "+" : ""}${results.deltas.quality_abs.toFixed(2)} |`,
    `| Voice similarity (cosine vs. maintainer) | ${m.voice_similarity_cosine.baseline.toFixed(3)} | **${m.voice_similarity_cosine.pipeline.toFixed(3)}** | ${results.deltas.voice_sim_abs >= 0 ? "+" : ""}${results.deltas.voice_sim_abs.toFixed(3)} |`,
    `| Avg time per issue | ${m.avg_ms_per_issue.baseline.toFixed(0)} ms | ${m.avg_ms_per_issue.pipeline.toFixed(0)} ms | — |`,
    ``,
    `> The pipeline's gain comes mostly from duplicate detection (the single agent has no retrieval, so it misclassifies paraphrased duplicates) and voice-matched drafting. The baseline is faster because it's one call; the pipeline trades latency for accuracy and quality, with the human gate as the backstop.`,
    `<!-- BENCHMARK:END -->`,
  ].join("\n");

  let md = readFileSync(path, "utf8");
  const re = /<!-- BENCHMARK:START -->[\s\S]*?<!-- BENCHMARK:END -->/;
  if (re.test(md)) {
    md = md.replace(re, table);
    writeFileSync(path, md);
    ok("README benchmark table regenerated");
  } else {
    ok("results written (add the <!-- BENCHMARK:START/END --> markers to README to auto-insert the table)");
  }
}

async function run() {
  banner("Agent Society benchmark");
  await ensureRuntime();
  const py = venvPython();
  if (!py) {
    fail("agent venv missing — run `npm run setup` first.");
    process.exit(1);
  }
  const r = spawnSync(py, [resolve(ROOT, "benchmarks/agent_society.py")], {
    cwd: ROOT,
    stdio: "inherit",
    env: { ...env, AGENTS_URL: AGENTS },
  });
  if (r.status !== 0) {
    fail("benchmark failed");
    process.exit(r.status ?? 1);
  }
  const results = JSON.parse(readFileSync(resolve(ROOT, "benchmarks/results.json"), "utf8"));
  regenReadme(results);
}

run()
  .catch((e) => { fail(e.message); process.exitCode = 1; })
  .finally(async () => {
    if (spawned.length) {
      await sleep(150);
      for (const ch of spawned) { try { ch.kill("SIGTERM"); } catch {} }
    }
  });
